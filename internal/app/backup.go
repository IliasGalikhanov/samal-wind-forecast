const backupLimit = 512 << 20

type BackupInfo struct {
	Format       string `json:"format"`
	Version      int    `json:"version"`
	Created      string `json:"created"`
	Observations int    `json:"observations"`
	Imports      int    `json:"imports"`
	Runs         int    `json:"runs"`
}

func (a *App) makeBackup(destination string) error {
	stage, err := os.MkdirTemp(filepath.Join(a.root, "runtime"), "backup-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(stage)
	database := filepath.Join(stage, "state.db")
	if _, err = a.db.Exec("VACUUM INTO ?", database); err != nil {
		return err
	}
	info := BackupInfo{Format: "samal", Version: 1, Created: now()}
	for table, p := range map[string]*int{"observations": &info.Observations, "imports": &info.Imports, "runs": &info.Runs} {
		if err = a.db.QueryRow("SELECT count(*) FROM " + table).Scan(p); err != nil {
			return err
		}
	}
	f, err := os.Create(destination)
	if err != nil {
		return err
	}
	defer f.Close()
	z := zip.NewWriter(f)
	add := func(name, path string) error {
		entry, e := z.Create(name)
		if e != nil {
			return e
		}
		source, e := os.Open(path)
		if e != nil {
			return e
		}
		defer source.Close()
		_, e = io.Copy(entry, source)
		return e
	}
	entry, err := z.Create("manifest.json")
	if err != nil {
		return err
	}
	if err = json.NewEncoder(entry).Encode(info); err != nil {
		return err
	}
	if err = add("state.db", database); err != nil {
		return err
	}
	for _, dir := range []string{"uploads", "runs"} {
		base := filepath.Join(a.root, "runtime", dir)
		err = filepath.WalkDir(base, func(path string, d os.DirEntry, e error) error {
			if e != nil {
				return e
			}
			if d.IsDir() {
				return nil
			}
			if !d.Type().IsRegular() {
				return errors.New("Unsupported backup file")
			}
			rel, e := filepath.Rel(filepath.Join(a.root, "runtime"), path)
			if e != nil {
				return e
			}
			return add(filepath.ToSlash(rel), path)
		})
		if err != nil {
			return err
		}
	}
	if err = z.Close(); err != nil {
		return err
	}
	return f.Sync()
}
func (a *App) downloadBackup(w http.ResponseWriter, r *http.Request) {
	if !a.work.TryLock() {
		problem(w, 409, errors.New("Дождитесь завершения текущего расчёта или импорта"))
		return
	}
	defer a.work.Unlock()
	path := filepath.Join(a.root, "runtime", "export-"+id()+".zip")
	defer os.Remove(path)
	if err := a.makeBackup(path); err != nil {
		problem(w, 500, err)
		return
	}
	w.Header().Set("Content-Disposition", `attachment; filename="samal-backup.zip"`)
	w.Header().Set("Content-Type", "application/zip")
	http.ServeFile(w, r, path)
}
func (a *App) downloadRecovery(w http.ResponseWriter, r *http.Request) {
	path := filepath.Join(a.root, "runtime", "recovery.zip")
	if _, err := os.Stat(path); err != nil {
		problem(w, 404, errors.New("Резервная копия не найдена"))
		return
	}
	w.Header().Set("Content-Disposition", `attachment; filename="samal-recovery.zip"`)
	w.Header().Set("Content-Type", "application/zip")
	http.ServeFile(w, r, path)
}

// Only paths generated by SAMAL can be extracted. Limits apply to actual bytes too.
func unpackBackup(archive, destination string) (BackupInfo, error) {
	var info BackupInfo
	z, err := zip.OpenReader(archive)
	if err != nil {
		return info, errors.New("Некорректный архив SAMAL")
	}
	defer z.Close()
	if len(z.File) > 20000 {
		return info, errors.New("Слишком много файлов в архиве")
	}
	seen := map[string]bool{}
	var total int64
	for _, f := range z.File {
		name := f.Name
		parts := strings.Split(name, "/")
		valid := name == "manifest.json" || name == "state.db" || (len(parts) == 2 && parts[0] == "uploads" && strings.HasSuffix(parts[1], ".csv")) || (len(parts) == 3 && parts[0] == "runs")
		for _, part := range parts {
			if part == "" || part == "." || part == ".." || strings.ContainsAny(part, `\:`) {
				valid = false
			}
		}
		// Run IDs are numeric; filenames are a fixed list, including CatBoost artifacts.
		if len(parts) == 3 {
			for _, c := range parts[1] {
				if c < '0' || c > '9' {
					valid = false
				}
			}
			switch parts[2] {
			case "input.csv", "result.json", "training-report.json", "validation-model.cbm", "model.cbm", "worker.log", "request.json", "weather-config.json", "weather.json", "weather-live.json", "weather-training.csv", "weather-forecast.json", "replay.csv", "catboost_weather.cbm", "catboost_weather_only.cbm", "catboost_mae.cbm", "validation-catboost_weather.cbm", "validation-catboost_weather_only.cbm", "validation-catboost_mae.cbm":
			default:
				valid = false
			}
		}
		if !valid || seen[strings.ToLower(name)] || !f.Mode().IsRegular() {
			return info, errors.New("Недопустимые файлы в архиве")
		}
		seen[strings.ToLower(name)] = true
		if f.UncompressedSize64 > uint64(2<<30) {
			return info, errors.New("Архив слишком большой")
		}
		target := filepath.Join(destination, filepath.FromSlash(name))
		if err = os.MkdirAll(filepath.Dir(target), 0755); err != nil {
			return info, err
		}
		source, e := f.Open()
		if e != nil {
			return info, e
		}
		out, e := os.Create(target)
		if e != nil {
			source.Close()
			return info, e
		}
		n, e := io.Copy(out, io.LimitReader(source, (2<<30)-total+1))
		source.Close()
		out.Close()
		total += n
		if e != nil {
			return info, e
		}
		if total > 2<<30 {
			return info, errors.New("Архив слишком большой")
		}
	}
	if !seen["state.db"] || !seen["manifest.json"] {
		return info, errors.New("В архиве нет данных SAMAL")
	}
	manifest, err := os.ReadFile(filepath.Join(destination, "manifest.json"))
	if err != nil {
		return info, err
	}
	if len(manifest) > 8192 || json.Unmarshal(manifest, &info) != nil || info.Format != "samal" || info.Version != 1 {
		return info, errors.New("Неподдерживаемая версия резервной копии")
	}
	db, err := sql.Open("sqlite", filepath.Join(destination, "state.db"))
	if err != nil {
		return info, err
	}
	defer db.Close()
	db.SetMaxOpenConns(1)
	if _, err = db.Exec("PRAGMA trusted_schema=OFF; PRAGMA query_only=ON;"); err != nil {
		return info, err
	}
	var check string
	if err = db.QueryRow("PRAGMA integrity_check").Scan(&check); err != nil || check != "ok" {
		return info, errors.New("Резервная копия повреждена")
	}
	for table, p := range map[string]*int{"observations": &info.Observations, "imports": &info.Imports, "runs": &info.Runs} {
		var typ string
		if err = db.QueryRow("SELECT type FROM sqlite_master WHERE name=?", table).Scan(&typ); err != nil || typ != "table" {
			return info, errors.New("Неверная структура резервной копии")
		}
		if err = db.QueryRow("SELECT count(*) FROM " + table).Scan(p); err != nil {
			return info, err
		}
	}
	// Validate the columns before touching the current database.
	for _, query := range []string{
		"SELECT id,name,latitude,longitude FROM turbines LIMIT 0",
		"SELECT turbine_id,time,wind,power,temperature FROM observations LIMIT 0",
		"SELECT id,turbine_id,name,created,rows,added,duplicates,sha256 FROM imports LIMIT 0",
		"SELECT id,status,created,trigger,horizon,origin,step,error,result,events FROM runs LIMIT 0",
	} {
		rows, e := db.Query(query)
		if e != nil {
			return info, errors.New("Неверная структура резервной копии")
		}
		rows.Close()
	}
	projection, err := backupTurbineProjection(db, "main")
	if err != nil {
		return info, err
	}
	stations, err := db.Query(projection)
	if err != nil {
		return info, err
	}
	for stations.Next() {
		var t Turbine
		if e := stations.Scan(&t.ID, &t.Name, &t.Latitude, &t.Longitude, &t.SampleMinutes, &t.RatedKW); e != nil || t.ID <= 0 || !validTurbine(t) {
			stations.Close()
			return info, errors.New("Некорректные турбины в архиве")
		}
	}
	err = stations.Err()
	stations.Close()
	if err != nil {
		return info, err
	}
	var invalid int
	if err = db.QueryRow("WITH config AS (" + projection + ") SELECT count(*) FROM observations o LEFT JOIN config t ON t.id=o.turbine_id WHERE t.id IS NULL OR power IS NULL OR wind IS NULL OR temperature IS NULL OR power NOT BETWEEN 0 AND 1 OR wind NOT BETWEEN 0 AND 100 OR temperature NOT BETWEEN -100 AND 100 OR strftime('%Y-%m-%d %H:%M:%S',time) IS NULL OR substr(time,18,2)!='00' OR cast(substr(time,15,2) AS integer)%t.sample_minutes!=0").Scan(&invalid); err != nil || invalid != 0 {
		return info, errors.New("Некорректные измерения в резервной копии")
	}
	if err = db.QueryRow("SELECT count(*) FROM runs WHERE status NOT IN ('completed','failed','cancelled') OR NOT json_valid(events) OR (result IS NOT NULL AND NOT json_valid(result))").Scan(&invalid); err != nil || invalid != 0 {
		return info, errors.New("Некорректные расчёты в резервной копии")
	}
	for _, dir := range []string{"uploads", "runs"} {
		if err = os.MkdirAll(filepath.Join(destination, dir), 0755); err != nil {
			return info, err
		}
	}
	return info, nil
}
func (a *App) receiveBackup(w http.ResponseWriter, r *http.Request) (string, BackupInfo, error) {
	var info BackupInfo
	r.Body = http.MaxBytesReader(w, r.Body, backupLimit)
	if err := r.ParseMultipartForm(8 << 20); err != nil {
		return "", info, errors.New("Не удалось прочитать архив. Максимум — 512 МБ")
	}
	if r.MultipartForm != nil {
		defer r.MultipartForm.RemoveAll()
	}
	f, _, err := r.FormFile("file")
	if err != nil {
		return "", info, errors.New("Выберите архив SAMAL")
	}
	defer f.Close()
	stage, err := os.MkdirTemp(filepath.Join(a.root, "runtime"), "restore-")
	if err != nil {
		return "", info, err
	}
	path := filepath.Join(stage, "source.zip")
	out, err := os.Create(path)
	if err != nil {
		os.RemoveAll(stage)
		return "", info, err
	}
	_, err = io.Copy(out, f)
	out.Close()
	if err == nil {
		info, err = unpackBackup(path, stage)
	}
	if err != nil {
		os.RemoveAll(stage)
		return "", info, err
	}
	return stage, info, nil
}
func (a *App) previewBackup(w http.ResponseWriter, r *http.Request) {
	stage, info, err := a.receiveBackup(w, r)
	if err != nil {
		problem(w, 422, err)
		return
	}
	defer os.RemoveAll(stage)
	respond(w, 200, info)
}
func (a *App) restoreBackup(w http.ResponseWriter, r *http.Request) {
	if !a.work.TryLock() {
		problem(w, 409, errors.New("Дождитесь завершения текущего расчёта или импорта"))
		return
	}
	defer a.work.Unlock()
	stage, info, err := a.receiveBackup(w, r)
	if err != nil {
		problem(w, 422, err)
		return
	}
	defer os.RemoveAll(stage)
	if r.FormValue("confirm") != "restore" {
		problem(w, 400, errors.New("Подтвердите восстановление"))
		return
	}
	recovery := filepath.Join(a.root, "runtime", "recovery.zip")
	pending := filepath.Join(stage, "recovery.zip")
	if err = a.makeBackup(pending); err != nil {
		problem(w, 500, err)
		return
	}
	// Rename replaces the previous recovery file on Windows as well.
	if err = os.Rename(pending, recovery); err != nil {
		problem(w, 500, err)
		return
	}
	if err = a.restoreState(stage); err != nil {
		problem(w, 422, err)
		return
	}
	respond(w, 200, info)
}
func (a *App) restoreState(stage string) error {
	if _, err := a.db.Exec("ATTACH DATABASE ? AS restored", filepath.Join(stage, "state.db")); err != nil {
		return err
	}
	defer a.db.Exec("DETACH DATABASE restored")
	tx, err := a.db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()
	// Older backups predate server settings. Preserve the current settings for them.
	var hasSettings int
	if err = tx.QueryRow("SELECT count(*) FROM restored.sqlite_master WHERE type='table' AND name='settings'").Scan(&hasSettings); err != nil {
		return err
	}
	if hasSettings > 0 {
		var source string
		_ = tx.QueryRow("SELECT value FROM restored.settings WHERE key='data_source'").Scan(&source)
		if (source == "synthetic") != a.demo {
			return errors.New("Нельзя смешивать демонстрационную базу и пользовательские данные")
		}
		var value string
		e := tx.QueryRow("SELECT value FROM restored.settings WHERE key='weather'").Scan(&value)
		if e == nil {
			var settings WeatherSettings
			if json.Unmarshal([]byte(value), &settings) != nil || !validWeatherSettings(settings) {
				return errors.New("Некорректные настройки погоды в архиве")
			}
			if _, err = tx.Exec("INSERT INTO settings(key,value) VALUES('weather',?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", value); err != nil {
				return err
			}
		} else if e == sql.ErrNoRows {
			if _, err = tx.Exec("DELETE FROM settings WHERE key='weather'"); err != nil {
				return err
			}
		} else {
			return e
		}
	}
	projection, err := backupTurbineProjection(tx, "restored")
	if err != nil {
		return err
	}
	for _, q := range []string{
		"DELETE FROM observations", "DELETE FROM imports", "DELETE FROM runs", "DELETE FROM turbines",
		"INSERT INTO turbines(id,name,latitude,longitude,sample_minutes,rated_kw) " + projection,
		"INSERT INTO observations SELECT turbine_id,time,wind,power,temperature FROM restored.observations",
		"INSERT INTO imports SELECT id,turbine_id,name,created,rows,added,duplicates,sha256 FROM restored.imports",
		"INSERT INTO runs SELECT id,status,created,trigger,horizon,origin,step,error,result,events FROM restored.runs",
	} {
		if _, err = tx.Exec(q); err != nil {
			return fmt.Errorf("Не удалось восстановить данные: %w", err)
		}
	}
	moved := []string{}
	rollbackFiles := func() {
		for i := len(moved) - 1; i >= 0; i-- {
			dir := moved[i]
			os.Rename(filepath.Join(a.root, "runtime", dir), filepath.Join(stage, "new-"+dir))
			os.Rename(filepath.Join(stage, "old-"+dir), filepath.Join(a.root, "runtime", dir))
		}
	}
	for _, dir := range []string{"uploads", "runs"} {
		target := filepath.Join(a.root, "runtime", dir)
		old := filepath.Join(stage, "old-"+dir)
		if err = os.Rename(target, old); err != nil {
			rollbackFiles()
			return err
		}
		if err = os.Rename(filepath.Join(stage, dir), target); err != nil {
			os.Rename(old, target)
			rollbackFiles()
			return err
		}
		moved = append(moved, dir)
	}
	if err = tx.Commit(); err != nil {
		rollbackFiles()
		return err
	}
	return nil
}

// Column defaults keep archives from the original two-turbine release readable.
func backupTurbineProjection(db interface{ QueryRow(string, ...any) *sql.Row }, namespace string) (string, error) {
	values := []string{"10", "0"}
	for i, column := range []string{"sample_minutes", "rated_kw"} {
		var count int
		if err := db.QueryRow("SELECT count(*) FROM pragma_table_info('turbines',?) WHERE name=?", namespace, column).Scan(&count); err != nil {
			return "", err
		}
		if count > 0 {
			values[i] = column
		}
	}
	return "SELECT id,name,latitude,longitude," + values[0] + " AS sample_minutes," + values[1] + " AS rated_kw FROM " + namespace + ".turbines", nil
}
